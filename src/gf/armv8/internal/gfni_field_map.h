#ifndef GFNI_FIELD_MAP_H
#define GFNI_FIELD_MAP_H

#include <stdint.h>

/* GF(16) = GF(2)[x]/(x^4+x+1) embedded in the AES/Rijndael byte field. */
static const uint8_t gfni_gf16_embed_scalar_table[16] = {
    0x00, 0x01, 0x5c, 0x5d, 0xe0, 0xe1, 0xbc, 0xbd,
    0x50, 0x51, 0x0c, 0x0d, 0xb0, 0xb1, 0xec, 0xed
};

/* MQOM v2.1.1 uses a separate, valid subfield coordinate map. */
static const uint8_t pqc_kernel_mqom_gf16_embed_scalar_table[16] = {
    0x00, 0x01, 0xe0, 0xe1, 0x5d, 0x5c, 0xbd, 0xbc,
    0xb0, 0xb1, 0x50, 0x51, 0xed, 0xec, 0x0d, 0x0c
};

#endif
