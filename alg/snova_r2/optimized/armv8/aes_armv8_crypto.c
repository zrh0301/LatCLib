static inline uint32_t bswap32_local(uint32_t x) {
    return ((x & 0x000000ffu) << 24) |
           ((x & 0x0000ff00u) << 8) |
           ((x & 0x00ff0000u) >> 8) |
           ((x & 0xff000000u) >> 24);
}

static void aes128_key_schedule_bytes(const uint8_t key[16],
                                      uint8_t round_keys[11][16]) {
    static const uint8_t rcon[10] = {
        0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36
    };

    memcpy(round_keys[0], key, 16);
    for (int r = 1; r <= 10; ++r) {
        uint8_t t[4];
        t[0] = aes_sbox[round_keys[r - 1][13]] ^ rcon[r - 1];
        t[1] = aes_sbox[round_keys[r - 1][14]];
        t[2] = aes_sbox[round_keys[r - 1][15]];
        t[3] = aes_sbox[round_keys[r - 1][12]];

        for (int i = 0; i < 4; ++i) {
            round_keys[r][i] = round_keys[r - 1][i] ^ t[i];
        }
        for (int i = 4; i < 16; ++i) {
            round_keys[r][i] = round_keys[r][i - 4] ^ round_keys[r - 1][i];
        }
    }
}

static inline uint8x16_t aes128_encrypt_block(uint8x16_t s,
                                              const uint8x16_t rk[11]) {
    s = vaeseq_u8(s, rk[0]); s = vaesmcq_u8(s);
    s = vaeseq_u8(s, rk[1]); s = vaesmcq_u8(s);
    s = vaeseq_u8(s, rk[2]); s = vaesmcq_u8(s);
    s = vaeseq_u8(s, rk[3]); s = vaesmcq_u8(s);
    s = vaeseq_u8(s, rk[4]); s = vaesmcq_u8(s);
    s = vaeseq_u8(s, rk[5]); s = vaesmcq_u8(s);
    s = vaeseq_u8(s, rk[6]); s = vaesmcq_u8(s);
    s = vaeseq_u8(s, rk[7]); s = vaesmcq_u8(s);
    s = vaeseq_u8(s, rk[8]); s = vaesmcq_u8(s);
    s = vaeseq_u8(s, rk[9]);
    return veorq_u8(s, rk[10]);
}

static inline uint8x16_t make_ctr_block(uint32x4_t base32, uint32_t ctr) {
    base32 = vsetq_lane_u32(bswap32_local(ctr), base32, 3);
    return vreinterpretq_u8_u32(base32);
}

int AES128_CTR(unsigned char *output, size_t outputByteLen,
               const unsigned char *input, size_t inputByteLen) {
    assert(inputByteLen > 0);

    uint8_t round_key_bytes[11][16];
    uint8x16_t rk[11];
    uint8_t base_bytes[16] = {0};
    uint32_t ctr = 0;
    unsigned char *out = output;
    size_t outlen = outputByteLen;

    aes128_key_schedule_bytes(input, round_key_bytes);
    for (int i = 0; i <= 10; ++i) {
        rk[i] = vld1q_u8(round_key_bytes[i]);
    }

    const uint32x4_t base32 = vreinterpretq_u32_u8(vld1q_u8(base_bytes));

    while (outlen >= 64) {
        uint8x16_t s0 = make_ctr_block(base32, ctr + 0);
        uint8x16_t s1 = make_ctr_block(base32, ctr + 1);
        uint8x16_t s2 = make_ctr_block(base32, ctr + 2);
        uint8x16_t s3 = make_ctr_block(base32, ctr + 3);

        vst1q_u8(out +  0, aes128_encrypt_block(s0, rk));
        vst1q_u8(out + 16, aes128_encrypt_block(s1, rk));
        vst1q_u8(out + 32, aes128_encrypt_block(s2, rk));
        vst1q_u8(out + 48, aes128_encrypt_block(s3, rk));

        ctr += 4;
        out += 64;
        outlen -= 64;
    }

    while (outlen >= 16) {
        uint8x16_t s = make_ctr_block(base32, ctr++);
        vst1q_u8(out, aes128_encrypt_block(s, rk));
        out += 16;
        outlen -= 16;
    }

    if (outlen > 0) {
        uint8_t tmp[16];
        uint8x16_t s = make_ctr_block(base32, ctr);
        vst1q_u8(tmp, aes128_encrypt_block(s, rk));
        memcpy(out, tmp, outlen);
    }

    return (int)outputByteLen;
}

