#include "test.h"
#include "keccak.h"
#include <stddef.h>

static void sha3_256_starts(void *ctx) {
    sha3_init((KECCAK1600_CTX *)ctx, 0x06, 256);
}

static void sha3_512_starts(void *ctx) {
    sha3_init((KECCAK1600_CTX *)ctx, 0x06, 512);
}

static void keccak_update_case(void *ctx, const uint8_t *input, size_t input_len) {
    sha3_update((KECCAK1600_CTX *)ctx, input, input_len);
}

static void keccak_finish_case(void *ctx, uint8_t *output) {
    sha3_final(output, (KECCAK1600_CTX *)ctx);
}

static void sha3_256_digest(uint8_t *output, const uint8_t *input, size_t input_len) {
    sha3_256(output, input, input_len);
}

static void sha3_512_digest(uint8_t *output, const uint8_t *input, size_t input_len) {
    sha3_512(output, input, input_len);
}

